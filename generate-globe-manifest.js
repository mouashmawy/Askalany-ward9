// Run after adding/removing photos: node generate-globe-manifest.js
const fs = require('node:fs');
const path = require('node:path');
const folder = path.join(__dirname, 'images', 'globe');
const photos = fs.readdirSync(folder).filter(name => /\.(webp|png|jpe?g|avif|gif)$/i.test(name))
  .sort((a, b) => a.localeCompare(b, undefined, {numeric: true}))
  .map(name => 'images/globe/' + name);
fs.writeFileSync(path.join(__dirname, 'globe-photos.js'), '// Generated by generate-globe-manifest.js\nwindow.globePhotos = ' + JSON.stringify(photos, null, 2) + ';\n');
console.log('Gallery manifest: ' + photos.length + ' photos');

